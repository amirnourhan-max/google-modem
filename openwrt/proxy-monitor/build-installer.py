#!/usr/bin/env python3
"""Generate the self-contained offline installer from reviewed payloads."""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parent
SRC = ROOT / 'src'
FILES = {
    '/usr/share/ucode/proxy-monitor.uc': ('data.uc', 'PMDATA', '0644'),
    '/usr/libexec/proxy-monitor-exit-check.uc': ('exit-check.uc', 'PMEXITCODE', '0644'),
    '/usr/libexec/proxy-monitor-exit': ('exit-check.sh', 'PMEXITSH', '0755'),
    '/usr/libexec/proxy-monitor-status': ('status.uc', 'UCODE', '0755'),
    '/www/luci-static/resources/view/status/include/00_proxy-monitor.js': ('proxy-monitor.js', 'LUCIJS', '0644'),
    '/usr/share/rpcd/ucode/proxy-monitor': ('rpc-plugin.uc', 'RPCPLUGIN', '0644'),
}
acl = {'luci-app-proxy-monitor': {'description': 'Read-only Proxy Monitor status',
    'read': {'ubus': {'proxy-monitor': ['status', 'exit_refresh']}}}}
payloads = [(p, (SRC / name).read_text(), mark, mode) for p, (name, mark, mode) in FILES.items()]
payloads += [('/usr/share/rpcd/acl.d/luci-app-proxy-monitor.json', json.dumps(acl, indent=2)+'\n', 'JSONACL', '0644'),
    ('/www/cgi-bin/proxy-monitor-mobile', (SRC / 'mobile.cgi').read_text(), 'JSONMOBILE', '0755')]
owned = [p for p, *_ in payloads] + ['/etc/proxy-monitor/mobile-token', '/tmp/proxy-monitor-exit.json',
    '/usr/libexec/rpcd/proxy-monitor',
    '/www/luci-static/resources/view/services/proxy-monitor.js',
    '/usr/share/luci/menu.d/luci-app-proxy-monitor.json',
    '/www/luci-static/resources/view/status/include/75_proxy-monitor.js', '/usr/libexec/proxy-monitor-traffic']
manifest = '\n'.join(owned)
script = '''#!/bin/sh
# Generated by build-installer.py. Offline, read-only Proxy Monitor v15.
set -eu
PATH=/usr/sbin:/usr/bin:/sbin:/bin
export PATH
umask 077
[ "$(id -u)" -eq 0 ] || { echo 'ERROR: root required'; exit 1; }
case "${1:-}" in ''|--mobile-api) ;; *) echo 'Usage: installer [--mobile-api]'; exit 1 ;; esac
command -v ucode >/dev/null || { echo 'ERROR: ucode missing'; exit 1; }
[ -x /bin/ubus ] && [ -x /etc/init.d/rpcd ] || { echo 'ERROR: rpcd/ubus missing'; exit 1; }
[ -r /usr/lib/rpcd/ucode.so ] || { echo 'ERROR: rpcd-mod-ucode missing; no changes made'; exit 1; }
ucode -e "import * as fs from 'fs'; import { cursor } from 'uci'; let c=cursor(); exit(fs.stat('/') ? 0 : 1);"
LOCK=/tmp/proxy-monitor-v15-install.lock
check_parents() {
    d=$(dirname "$1")
    while [ "$d" != / ]; do
        [ ! -L "$d" ] || { echo "ERROR: symlink parent $d"; return 1; }
        d=$(dirname "$d")
    done
}
check_parents /tmp/proxy-monitor-v15-install.lock
check_parents /root/recovery/snapshot
mkdir "$LOCK" 2>/dev/null || { echo 'ERROR: installation lock exists'; exit 1; }
B=''
MUTATED=0
COMMITTED=0
cleanup() {
    rc=$?
    trap - EXIT HUP INT TERM
    if [ "$MUTATED" = 1 ] && [ "$COMMITTED" = 0 ]; then
        echo 'ERROR: deployment failed; restoring snapshot'
        sh "$B/rollback.sh" --held-lock || echo "ERROR: automatic restore incomplete; run $B/rollback.sh"
    fi
    rmdir "$LOCK" 2>/dev/null || true
    exit "$rc"
}
trap cleanup EXIT
trap 'exit 1' HUP INT TERM
[ ! -e /tmp/proxy-monitor-exit.lock ] || { echo 'ERROR: manual exit check busy; retry after it finishes'; exit 1; }
mkdir -p /root/recovery
B=$(mktemp -d /root/recovery/proxy-monitor-v15-XXXXXXXX)
mkdir -p "$B/originals" "$B/stage"
cat > "$B/manifest" <<'MANIFEST'
''' + manifest + '''
MANIFEST
while IFS= read -r p; do
    check_parents "$p"
    [ ! -L "$p" ] || { echo "ERROR: symlink destination $p"; exit 1; }
    [ ! -e "$p" ] || [ -f "$p" ] || { echo "ERROR: non-file destination $p"; exit 1; }
    if [ -f "$p" ]; then
        mkdir -p "$B/originals$(dirname "$p")"
        cp -p "$p" "$B/originals$p"
    fi
done < "$B/manifest"
cat > "$B/rollback.sh" <<'ROLLBACK'
#!/bin/sh
set -eu
PATH=/usr/sbin:/usr/bin:/sbin:/bin
export PATH
B="$(CDPATH= cd "$(dirname "$0")" && pwd)"
LOCK=/tmp/proxy-monitor-v15-install.lock
if [ "${1:-}" != --held-lock ]; then
    mkdir "$LOCK" 2>/dev/null || { echo 'ERROR: installation/rollback lock exists'; exit 1; }
    trap 'rmdir "$LOCK" 2>/dev/null || true' EXIT
fi
[ ! -e /tmp/proxy-monitor-exit.lock ] || { echo 'ERROR: manual exit check busy; retry rollback after it finishes'; exit 1; }
check_parents() {
    d=$(dirname "$1")
    while [ "$d" != / ]; do
        [ ! -L "$d" ] || { echo "ERROR: symlink parent $d"; return 1; }
        d=$(dirname "$d")
    done
}
atomic_copy() {
    tmp=$(mktemp "$2.pm-v15-XXXXXXXX")
    if ! cp -p "$1" "$tmp" || ! mv -f "$tmp" "$2"; then
        rm -f "$tmp"; return 1
    fi
}
while IFS= read -r p; do
    check_parents "$p"
    [ ! -L "$p" ] || { echo "ERROR: refuse symlink $p"; exit 1; }
    if [ -f "$B/originals$p" ]; then
        mkdir -p "$(dirname "$p")"
        atomic_copy "$B/originals$p" "$p"
    else rm -f "$p"; fi
done < "$B/manifest"
rm -f /tmp/luci-indexcache
rm -rf /tmp/luci-modulecache
/etc/init.d/rpcd restart
echo "Proxy Monitor restored: $B"
ROLLBACK
chmod 0700 "$B/rollback.sh"
'''
for path, data, marker, mode in payloads:
    script += f'mkdir -p "$B/stage{Path(path).parent}"\ncat > "$B/stage{path}" <<\'{marker}\'\n{data}{marker}\nchmod {mode} "$B/stage{path}"\n'
script += '''
# Compile and execute the staged backend before any production writes.
ucode -L "$B/stage/usr/share/ucode/*.uc" -c -o "$B/stage/data.ucb" -e 'import * as data from "proxy-monitor";'
ucode -L "$B/stage/usr/share/ucode/*.uc" -c -o "$B/stage/exit.ucb" "$B/stage/usr/libexec/proxy-monitor-exit-check.uc"
ucode -L "$B/stage/usr/share/ucode/*.uc" -c -o "$B/stage/backend.ucb" "$B/stage/usr/libexec/proxy-monitor-status"
ucode -L "$B/stage/usr/share/ucode/*.uc" -c -o "$B/stage/rpc-plugin.ucb" "$B/stage/usr/share/rpcd/ucode/proxy-monitor"
ucode -L "$B/stage/usr/share/ucode/*.uc" -e 'import * as fs from "fs"; let d=loadstring(fs.stdin.read("all"))(); exit(type(d["proxy-monitor"].status.call) == "function" && type(d["proxy-monitor"].exit_refresh.call) == "function" ? 0 : 1);' < "$B/stage/usr/share/rpcd/ucode/proxy-monitor"
ucode -L "$B/stage/usr/share/ucode/*.uc" "$B/stage/usr/libexec/proxy-monitor-status" > "$B/stage/status.json"
ucode -e 'import * as fs from "fs"; let d=json(fs.stdin.read("all")); exit(d.backend_version == 15 && type(d.active_nodes) == "array" ? 0 : 1);' < "$B/stage/status.json"
ucode -L "$B/stage/usr/share/ucode/*.uc" "$B/stage/usr/libexec/proxy-monitor-status" --mobile > "$B/stage/mobile.json"
ucode -e 'import * as fs from "fs"; let d=json(fs.stdin.read("all")); exit(d.api_version == 7 && d.traffic.available == false ? 0 : 1);' < "$B/stage/mobile.json"
for p in /usr/share/rpcd/acl.d/luci-app-proxy-monitor.json; do
    ucode -e 'import * as fs from "fs"; exit(type(json(fs.stdin.read("all"))) == "object" ? 0 : 1);' < "$B/stage$p"
done
MOBILE=0
if [ -f /www/cgi-bin/proxy-monitor-mobile ] || [ "${1:-}" = --mobile-api ]; then
    MOBILE=1
    mkdir -p "$B/stage/etc/proxy-monitor"
    if [ -f /etc/proxy-monitor/mobile-token ]; then
        cp /etc/proxy-monitor/mobile-token "$B/stage/etc/proxy-monitor/mobile-token"
    else
        od -An -N32 -tx1 /dev/urandom | tr -d ' \\n' > "$B/stage/etc/proxy-monitor/mobile-token"
        printf '\\n' >> "$B/stage/etc/proxy-monitor/mobile-token"
    fi
    TOKEN=$(cat "$B/stage/etc/proxy-monitor/mobile-token")
    [ "${#TOKEN}" -eq 64 ] || { echo 'ERROR: invalid mobile token'; exit 1; }
    case "$TOKEN" in *[!a-f0-9]*) echo 'ERROR: invalid mobile token'; exit 1 ;; esac
    chmod 0600 "$B/stage/etc/proxy-monitor/mobile-token"
fi
atomic_copy() {
    tmp=$(mktemp "$2.pm-v15-XXXXXXXX")
    if ! cp -p "$1" "$tmp" || ! mv -f "$tmp" "$2"; then
        rm -f "$tmp"; return 1
    fi
}
MUTATED=1
while IFS= read -r p; do
    case "$p" in
        /www/cgi-bin/proxy-monitor-mobile|/etc/proxy-monitor/mobile-token) [ "$MOBILE" = 1 ] || continue ;;
    esac
    if [ -f "$B/stage$p" ]; then
        mkdir -p "$(dirname "$p")"
        atomic_copy "$B/stage$p" "$p"
    fi
done < "$B/manifest"
# Android CGI has been migrated before removing this legacy on-demand collector.
rm -f /www/luci-static/resources/view/status/include/75_proxy-monitor.js
rm -f /www/luci-static/resources/view/services/proxy-monitor.js
rm -f /usr/share/luci/menu.d/luci-app-proxy-monitor.json
rm -f /usr/libexec/rpcd/proxy-monitor
rm -f /usr/libexec/proxy-monitor-traffic
rm -f /tmp/luci-indexcache
rm -rf /tmp/luci-modulecache
/etc/init.d/rpcd restart
# procd restart returns before rpcd has reconnected and loaded plugins.
# Wait for the NEW native plugin signature, not just an old object name.
attempt=0
while :; do
    if /bin/ubus -t 2 call proxy-monitor status > "$B/stage/rpc-status.json" 2> "$B/stage/rpc-error.txt" &&
       ucode -e 'import * as fs from "fs"; try { let d=json(fs.stdin.read("all")); exit(d.backend_version == 15 && d.rpc_backend == "ucode" && d.rpc_revision == 3 ? 0 : 1); } catch(e) { exit(1); }' < "$B/stage/rpc-status.json"; then
        break
    fi
    attempt=$((attempt + 1))
    if [ "$attempt" -ge 10 ]; then
        echo 'ERROR: native rpcd plugin registration/status not ready after 10 bounded attempts'
        cat "$B/stage/rpc-error.txt" >&2
        ls -l /usr/lib/rpcd/ucode.so /usr/share/rpcd/ucode/proxy-monitor >&2 || true
        exit 1
    fi
    sleep 1
done
COMMITTED=1
echo 'Proxy Monitor v15 installed: Status > Overview (above System)'
echo "Backup/rollback: sh $B/rollback.sh"
if [ "$MOBILE" = 1 ]; then
    echo 'Mobile API v7: add ?token=<contents of /etc/proxy-monitor/mobile-token> to Android URL.'
fi
echo 'Only rpcd refreshed. Router page and internet health still require local verification.'
'''
(ROOT / 'install-proxy-monitor-v15.sh').write_text(script)
